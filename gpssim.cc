#define UART_ID uart0
#define BAUD_RATE 4800
#define UART_TX_PIN 0
#define UART_RX_PIN 1

int main() {
  bool state = false;
  const int LED = CYW43_WL_GPIO_LED_PIN;
  cyw43_arch_init();
  stdio_init_all();
  cyw43_arch_gpio_put(LED, state);
  sleep_ms(5000);
  char eof[4] = {0,0,0,0};
  gpio_set_function(UART_TX_PIN, UART_FUNCSEL_NUM(UART_ID, UART_TX_PIN));
  gpio_set_function(UART_RX_PIN, UART_FUNCSEL_NUM(UART_ID, UART_RX_PIN));
  int baud = uart_init(UART_ID, BAUD_RATE);
  printf("Initialized - UART set to: %d baud\n", baud);
  while (true) {
      char c = readchar();
      eof[0] = eof[1];
      eof[1] = eof[2];
      eof[2] = eof[3];
      eof[3] = c;
      if (strncmp(eof, "EOF", 3) == 0) {
	state = ! state;
	cyw43_arch_gpio_put(LED, state);
        gpsindex = 0;  // start over
	printf("Reseting message index\n");
	if (uart_is_writable(UART_ID)) {
	  uart_putc(UART_ID, c);
	  printf("Wrote, %d\n", c);
	} else {
	  printf("Can't write\n");
	}
      } else {
	state = ! state;
	cyw43_arch_gpio_put(LED, state);
	bool success = false;
	do {
	  if (uart_is_writable(UART_ID)) {
	    uart_putc_raw(UART_ID, c);
	    printf("Wrote, %d\n", c);
	    success = true;
	  } else {
	    printf("Can't write\n");
	    sleep_ms(10);
	  }
	} while (! success);
      }
  }
  return 0;
}
